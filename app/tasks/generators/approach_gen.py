def _stems(text: str) -> list[str]:
    return [w for w in re.findall(r"[a-zа-яё0-9+#.-]{4,}", text.lower())]


def pick_archetype(rng: random.Random, language: str, ctx_text: str) -> str:
    cands = [k for k, a in ARCHETYPES.items() if language in a["languages"]]
    text = (ctx_text or "").lower()
    scores = {k: sum(text.count(e) for e in ARCHETYPES[k]["evidence"]) for k in cands}
    best = max(scores.values()) if scores else 0
    pool = [k for k in cands if scores[k] == best] if best > 0 else cands
    return rng.choice(sorted(pool))


def build_approach(language: str):
    def build(rng: random.Random, ctx: ContextPack, grade: str, seed: int) -> TaskSpec:
        key = pick_archetype(rng, language, ctx.text)
        arch = ARCHETYPES[key]
        level = grade if grade in _GRADE_ASK else "middle"
        rubric = list(arch["rubric"]) + (list(arch["senior"]) if level in ("senior", "lead") else []) + \
            (list(arch["lead"]) if level == "lead" else [])
        lang_note = "" if language == "sql" else f" Язык реализации: {'Python' if language == 'python' else 'Java'}."
        variant = rng.choice(["", " Ограничение: решение должно работать на одном сервере с 2 ГБ памяти.",
                              " Ограничение: решение должно выдерживать рост нагрузки в 10 раз.",
                              " Ограничение: время на реализацию — один рабочий день."])
        statement = f"{arch['statement']}{lang_note}{variant}\n{_GRADE_ASK[level]}"
        return TaskSpec(
            f"approach.{language}.{key}", Kind.APPROACH, language, grade, f"approach_{key}", seed, statement,
            public={"title": arch["title"], "min_chars": 400, "max_chars": 4000},
            private={"rubric": [{"point": p, "keywords": kw, "min_hits": 1, "weight": 1.0} for p, kw in rubric]},
            difficulty={"middle": 0.5, "senior": 1.2, "lead": 1.9}[level], weight=1.5, time_limit_s=900,
            manual_review=level in ("senior", "lead"), sources=list(ctx.sources[:3]),
        )
    return build


def approach_generators() -> list[GeneratorDef]:
    out = []
    for language in ("python", "java", "sql"):
        keywords = tuple(sorted({e for a in ARCHETYPES.values() if language in a["languages"] for e in a["evidence"]}))
        out.append(GeneratorDef(f"approach.{language}", language, Kind.APPROACH, "approach", ("middle", "senior", "lead"),
                                1.0, keywords, build_approach(language), time_limit_s=900, weight=1.5))
    return out
